if(!i.value.trim())msg='Please fill in this field.';
else if(i.type==='email'&&!/^\S+@\S+\.\S+$/.test(i.value))msg='Enter a valid email address.';
else if(i.type==='tel'&&!/^[+\d][\d\s-]{6,}$/.test(i.value))msg='Enter a valid phone number.';
